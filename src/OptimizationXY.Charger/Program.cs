// =============================================================================
// Program.cs - application entry point
// -----------------------------------------------------------------------------
// This is the first code that runs when OptimizationXY.Charger.exe starts.
//
// What it does, in order:
//   1. Makes sure only ONE copy of the program is running (two copies would
//      fight over the same cameras and the same PLC connection).
//   2. Creates the data folders (Config, Logs, SavedScans, ...) under
//      ApplicationPaths.RootDirectory and starts NLog logging there.
//   3. Installs "last chance" exception handlers so a crash is logged and the
//      program shuts down cleanly instead of running in an unknown state.
//   4. Loads appsettings.json into PipelineState.Instance.Settings (the one
//      shared settings object every service reads).
//   5. Looks at the command line. Three "headless" modes run without the
//      operator screen, cameras or PLC and then exit:
//        --import-calibration-images ... -> CalibrationImageImportRunner
//        --replay-batch ...              -> BatchReplayRunner
//        --replay ...                    -> OfflineReplayRunner
//      (--set Name=Value can be added to replays to try a setting change.)
//   6. Otherwise opens MainForm, the normal operator screen used on the
//      production computer.
// =============================================================================

using NLog;
using OptimizationXY.Charger.Infrastructure;
using OptimizationXY.Charger.Services.Configuration;
using OptimizationXY.Charger.Services.Core;
using OptimizationXY.Charger.UI;

namespace OptimizationXY.Charger;

/// <summary>
/// The main entry point for the application.
/// </summary>
/// <remarks>
/// Keep this class small. All real work lives in the services under
/// <c>Services/</c>; this class only decides which top-level mode to start.
/// </remarks>
internal static class Program
{
    private static readonly Logger Logger = LogManager.GetCurrentClassLogger();

    /// <summary>
    /// Program start. <c>[STAThread]</c> is required by Windows Forms (the UI and
    /// clipboard/dialog components must run on a single-threaded apartment thread).
    /// </summary>
    [STAThread]
    private static void Main()
    {
        // A named, machine-wide mutex acts as a "this program is already running"
        // flag. If createdNew is false another instance already owns it, so this
        // second copy shows a warning and exits without touching cameras or the PLC.
        using var instanceMutex = new Mutex(
            initiallyOwned: true,
            name: @"Arbor.OptimizationXY.Charger.SingleInstance",
            createdNew: out bool createdNew);

        if (!createdNew)
        {
            MessageBox.Show(
                "Optimization XY Charger is already running. A second controller instance is blocked.",
                "Optimization XY Charger",
                MessageBoxButtons.OK,
                MessageBoxIcon.Warning);
            return;
        }

        // ApplicationConfiguration.Initialize() is generated by the WinForms SDK:
        // it turns on visual styles, default fonts and high-DPI settings.
        ApplicationConfiguration.Initialize();

        try
        {
            ApplicationPaths.EnsureCreated();
            ConfigureLogging();
            ConfigureGlobalExceptionHandling();
            Logger.Info("Optimization XY Charger starting.");

            // Load the saved settings (or create defaults on the very first run). Every
            // service reads its settings from this single shared object.
            PipelineState.Instance.Settings =
                AppSettingsStore.LoadOrCreateDefault();

            // Read the command line once. Each runner below checks for its own switch;
            // the first one that matches runs and the program exits without showing
            // the operator form.
            string[] commandLine = Environment.GetCommandLineArgs();

            // Mode 1 - build a calibration from saved reference images: no cameras, no PLC.
            if (OptimizationXY.Charger.Services.Calibration.CalibrationImageImportRunner.IsRequested(commandLine))
            {
                Logger.Info("Calibration image import requested; the operator form will not be opened.");
                OptimizationXY.Charger.Services.Calibration.CalibrationImageImportRunner.Run(commandLine);
                return;
            }

            // Mode 2 - batch replay: re-run many saved scans and write a comparison
            // report (used to check repeatability after a code change).
            if (OptimizationXY.Charger.Services.Replay.BatchReplayRunner.IsRequested(commandLine))
            {
                Logger.Info("Batch replay requested; the operator form will not be opened.");
                OptimizationXY.Charger.Services.Replay.BatchReplayRunner.Run(commandLine);
                return;
            }

            // Mode 3 - offline replay of ONE saved scan: no cameras, no PLC, no SQL.
            if (OptimizationXY.Charger.Services.Replay.OfflineReplayRunner.IsRequested(commandLine))
            {
                Logger.Info("Offline replay requested; the operator form will not be opened.");
                OptimizationXY.Charger.Services.Replay.OfflineReplayRunner.Run(commandLine);
                return;
            }

            // Normal mode: open the operator screen. Application.Run blocks here until
            // MainForm closes.
            Application.Run(new MainForm());
        }
        // Anything thrown during startup (bad settings file, missing NLog.config,
        // folder permissions, ...) ends up here: log it and tell the operator.
        catch (Exception ex)
        {
            Logger.Fatal(ex, "Application startup failed.");
            ShowFatalError(ex);
        }
        // Always flush and close the log files, even after a crash, so the last
        // messages are not lost.
        finally
        {
            Logger.Info("Optimization XY Charger stopped.");
            LogManager.Shutdown();
        }
    }

    /// <summary>
    /// Starts NLog using the NLog.config file installed beside the .exe and
    /// points its "logDirectory" variable at <see cref="ApplicationPaths.LogDirectory"/>
    /// so logs go to the writable data folder, not the ClickOnce install folder.
    /// Throws if NLog.config is missing - running without logs is not allowed.
    /// </summary>
    private static void ConfigureLogging()
    {
        ApplicationPaths.EnsureCreated();

        string configPath = Path.Combine(
            AppContext.BaseDirectory,
            "NLog.config");

        if (!File.Exists(configPath))
        {
            throw new FileNotFoundException(
                $"NLog configuration file was not found: {configPath}",
                configPath);
        }

        LogManager.Setup()
            .LoadConfigurationFromFile(configPath);

        if (LogManager.Configuration is null)
        {
            throw new InvalidOperationException(
                $"NLog failed to load its configuration from: {configPath}");
        }

        LogManager.Configuration.Variables["logDirectory"] =
            ApplicationPaths.LogDirectory;

        LogManager.ReconfigExistingLoggers();

        Logger.Info(
            "NLog initialized. Log directory: {0}",
            ApplicationPaths.LogDirectory);
    }
    /// <summary>
    /// Installs the three .NET "unhandled exception" hooks:
    /// <list type="bullet">
    /// <item><description>UI thread exceptions: logged, shown, then the program exits (fail closed).</description></item>
    /// <item><description>Background thread exceptions: logged as fatal (.NET will end the process).</description></item>
    /// <item><description>Forgotten (unobserved) Task exceptions: logged and marked observed so they do not crash the program.</description></item>
    /// </list>
    /// </summary>
    private static void ConfigureGlobalExceptionHandling()
    {
        Application.SetUnhandledExceptionMode(
            UnhandledExceptionMode.CatchException);

        Application.ThreadException += (_, args) =>
        {
            Logger.Error(args.Exception, "Unhandled UI thread exception.");
            ShowFatalError(args.Exception);

            // Fail closed after an unhandled UI exception. Continuing the
            // operator process with unknown state is not acceptable for a
            // machine-control application. Form shutdown disposes the single
            // PLC connection and stops camera acquisition.
            Application.Exit();
        };

        AppDomain.CurrentDomain.UnhandledException += (_, args) =>
        {
            Exception exception = args.ExceptionObject as Exception ??
                new InvalidOperationException(
                    $"Unhandled exception object: {args.ExceptionObject}");

            Logger.Fatal(exception, "Unhandled application-domain exception.");
        };

        TaskScheduler.UnobservedTaskException += (_, args) =>
        {
            Logger.Error(args.Exception, "Unobserved task exception.");
            args.SetObserved();
        };
    }

    /// <summary>
    /// Shows a message box with the error text and where the log files are, so
    /// the operator (or whoever is called) knows where to look.
    /// </summary>
    private static void ShowFatalError(Exception exception)
    {
        MessageBox.Show(
            "Optimization XY Charger encountered an unexpected error." +
            Environment.NewLine +
            $"Log directory (when logging initialized):{Environment.NewLine}" +
            ApplicationPaths.LogDirectory + Environment.NewLine + Environment.NewLine +
            exception.Message,
            "Optimization XY Charger",
            MessageBoxButtons.OK,
            MessageBoxIcon.Error);
    }
}
